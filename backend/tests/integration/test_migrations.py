"""Migrations are the only schema path -- never `create_all` (plan Section 2)."""

from __future__ import annotations

import asyncio

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine

pytestmark = pytest.mark.integration


async def test_alembic_upgrade_head_creates_the_version_table(engine: AsyncEngine) -> None:
    from app.db.migrate import run_migrations

    await run_migrations()

    async with engine.connect() as conn:
        result = await conn.execute(
            text("SELECT to_regclass('public.alembic_version') IS NOT NULL AS present")
        )
        assert result.scalar_one() is True


async def test_migrations_are_idempotent(engine: AsyncEngine) -> None:
    from app.db.migrate import run_migrations

    await run_migrations()
    await run_migrations()

    async with engine.connect() as conn:
        result = await conn.execute(text("SELECT count(*) FROM alembic_version"))
        assert result.scalar_one() == 1


async def test_models_match_migrations_with_no_drift(engine: AsyncEngine) -> None:
    """Guards against a model change landing without its migration.

    `alembic check` compares the models to the migrated schema; any difference
    means someone edited a model and forgot to autogenerate.
    """
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected
    from app.db.migrate import _alembic_config, run_migrations

    await run_migrations()

    try:
        await asyncio.to_thread(command.check, _alembic_config())
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Models and migrations have drifted: {exc}")
